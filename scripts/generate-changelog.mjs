// Runs before every build. Reads the real git history and writes
// src/generated/changelog.ts, so Super Admin > Changelog is always in sync
// with what actually shipped — nobody has to remember to hand-edit an entry.
import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const RS = "\x1e"; // record separator between commits
const FS = "\x1f"; // field separator between commit fields

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "..");
const outDir = join(repoRoot, "src", "generated");
const outFile = join(outDir, "changelog.ts");

function readGitLog() {
  try {
    const raw = execFileSync(
      "git",
      ["log", `--pretty=format:%ad${FS}%s${FS}%b${RS}`, "--date=format:%d %b %Y"],
      { cwd: repoRoot, encoding: "utf8", maxBuffer: 20 * 1024 * 1024 }
    );
    return raw;
  } catch (e) {
    console.warn("generate-changelog: git log failed, keeping any existing generated file.", e.message);
    return null;
  }
}

function parse(raw) {
  return raw
    .split(RS)
    .map((rec) => rec.trim())
    .filter(Boolean)
    .map((rec) => {
      const [date, title, body = ""] = rec.split(FS);
      const points = body
        .split("\n")
        .map((l) => l.replace(/^[-*]\s*/, "").trim())
        .filter(Boolean);
      return { date, title, points };
    });
}

function toSource(entries) {
  const json = JSON.stringify(entries, null, 2);
  return `// AUTO-GENERATED by scripts/generate-changelog.mjs from git log — do not edit by hand.
// Regenerated on every build, so this always matches what actually shipped.
export interface ChangelogEntry {
  date: string;
  title: string;
  points: string[];
}
export const CHANGELOG: ChangelogEntry[] = ${json};
`;
}

const raw = readGitLog();
if (raw !== null) {
  const entries = parse(raw);
  mkdirSync(outDir, { recursive: true });
  writeFileSync(outFile, toSource(entries), "utf8");
  console.log(`generate-changelog: wrote ${entries.length} entries to src/generated/changelog.ts`);
}
